"use client";

import { Fragment, useRef, useState } from "react";
import { CopyButton } from "@/components/copy-button";
import { Sparkles, X } from "@/components/icons";

type State = "idle" | "streaming" | "done" | "error";

// "Summarise with AI": streams a Markdown summary from the server and renders
// it as it arrives. Stop cancels both this fetch and the upstream AI call.
export function AiSummary({ projectId }: { projectId: string }) {
  const [state, setState] = useState<State>("idle");
  const [text, setText] = useState("");
  const [error, setError] = useState<string | null>(null);
  const abortRef = useRef<AbortController | null>(null);

  async function run() {
    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;
    setText("");
    setError(null);
    setState("streaming");

    try {
      const res = await fetch(`/api/projects/${projectId}/summary`, { method: "POST", signal: controller.signal });
      if (!res.ok || !res.body) {
        const data = await res.json().catch(() => ({}));
        throw new Error(data.error ?? "Couldn't generate a summary.");
      }
      const reader = res.body.getReader();
      const decoder = new TextDecoder();
      for (;;) {
        const { done, value } = await reader.read();
        if (done) break;
        setText((t) => t + decoder.decode(value, { stream: true }));
      }
      setState("done");
    } catch (err) {
      if ((err as Error).name === "AbortError") {
        setState((s) => (s === "streaming" ? "done" : s));
        return;
      }
      setError((err as Error).message);
      setState("error");
    }
  }

  const stop = () => abortRef.current?.abort();

  if (state === "idle") {
    return (
      <button
        type="button"
        onClick={run}
        className="group inline-flex items-center gap-2 rounded-xl border border-border bg-card px-3.5 py-2 text-sm font-semibold transition hover:border-accent/60"
      >
        <Sparkles className="text-accent transition group-hover:rotate-12" />
        Summarise with AI
      </button>
    );
  }

  return (
    <section
      aria-live="polite"
      aria-busy={state === "streaming"}
      className="relative overflow-hidden rounded-2xl border border-accent/30 bg-card p-5"
    >
      <div className="pointer-events-none absolute -top-20 -right-20 size-56 rounded-full bg-accent/10 blur-3xl" />
      <div className="relative flex items-center justify-between gap-3">
        <h2 className="flex items-center gap-2 font-semibold">
          <Sparkles className="text-accent" />
          AI summary
          {state === "streaming" && <span className="text-sm font-normal text-muted">writing…</span>}
        </h2>
        <div className="flex items-center gap-2">
          {state === "streaming" ? (
            <button type="button" onClick={stop} className="rounded-lg border border-border px-2.5 py-1 text-xs font-medium hover:border-foreground/30">
              Stop
            </button>
          ) : (
            <>
              {text && <CopyButton text={text} />}
              <button type="button" onClick={run} className="rounded-lg border border-border px-2.5 py-1 text-xs font-medium hover:border-foreground/30">
                Regenerate
              </button>
            </>
          )}
          <button
            type="button"
            aria-label="Close summary"
            onClick={() => {
              stop();
              setState("idle");
            }}
            className="text-muted hover:text-foreground"
          >
            <X />
          </button>
        </div>
      </div>

      {state === "error" ? (
        <p role="alert" className="relative mt-3 text-sm text-red-600 dark:text-red-400">
          {error}
        </p>
      ) : (
        <div className="relative mt-3 text-sm leading-relaxed">
          {text ? <Markdown source={text} /> : <SummarySkeleton />}
          {state === "streaming" && text && <span className="ml-0.5 inline-block h-4 w-1.5 animate-pulse bg-accent align-middle" />}
        </div>
      )}
      <p className="relative mt-4 text-xs text-muted">Generated by AI from your top-voted feedback. Check before acting on it.</p>
    </section>
  );
}

function SummarySkeleton() {
  return (
    <div className="flex flex-col gap-2" aria-hidden="true">
      {[70, 90, 55].map((w) => (
        <div key={w} className="h-3 animate-pulse rounded bg-subtle" style={{ width: `${w}%` }} />
      ))}
    </div>
  );
}

// Minimal Markdown (## headings, - bullets, **bold**) rendered as React
// elements. Never dangerouslySetInnerHTML: model output is untrusted.
export function Markdown({ source }: { source: string }) {
  const blocks: React.ReactNode[] = [];
  let bullets: string[] = [];
  const flush = () => {
    if (bullets.length) {
      blocks.push(
        <ul key={`ul${blocks.length}`} className="mb-3 list-disc space-y-1 pl-5 marker:text-accent">
          {bullets.map((b, i) => (
            <li key={i}>{inline(b)}</li>
          ))}
        </ul>,
      );
      bullets = [];
    }
  };
  for (const raw of source.split("\n")) {
    const line = raw.trim();
    if (/^[-*•]\s+/.test(line)) {
      bullets.push(line.replace(/^[-*•]\s+/, ""));
      continue;
    }
    flush();
    if (!line) continue;
    const heading = line.match(/^#{1,4}\s+(.*)$/);
    blocks.push(
      heading ? (
        <h3 key={blocks.length} className="mt-1 mb-1.5 font-semibold">
          {inline(heading[1])}
        </h3>
      ) : (
        <p key={blocks.length} className="mb-3">
          {inline(line)}
        </p>
      ),
    );
  }
  flush();
  return <>{blocks}</>;
}

function inline(text: string) {
  return text.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? (
      <strong key={i}>{part.slice(2, -2)}</strong>
    ) : (
      <Fragment key={i}>{part}</Fragment>
    ),
  );
}
